// Write files
Object.entries(translations).forEach(([code, trans]) => {
  const dir = path.join(localesDir, code);
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
  }
  const filePath = path.join(dir, 'common.json');
  
  // Merge if exists
  let finalContent = trans;
  if (fs.existsSync(filePath)) {
    try {
      const existing = JSON.parse(fs.readFileSync(filePath, 'utf8'));
      finalContent = { ...existing, ...trans };
    } catch (e) {}
  }
  
  fs.writeFileSync(filePath, JSON.stringify(finalContent, null, 2));
  console.log(`Generated/Updated ${code}/common.json`);
});
